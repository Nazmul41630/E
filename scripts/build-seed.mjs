import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
import { categories, products } from '../src/data/products.js';
import { DEFAULT_BANNERS } from '../src/data/banners.js';
import { SOCIAL_CHANNELS } from '../src/data/social.js';
import { DEFAULT_SETTINGS } from '../src/data/settings.js';

const q = (value) => {
  if (value === null || value === undefined) return 'NULL';
  if (typeof value === 'number') return Number.isFinite(value) ? String(value) : 'NULL';
  if (typeof value === 'boolean') return value ? '1' : '0';
  return `'${String(value).replace(/'/g, "''")}'`;
};

const lines = ['-- generated by scripts/build-seed.mjs', 'DELETE FROM products;', 'DELETE FROM categories;', 'DELETE FROM banners;'];

categories.forEach((c, i) => {
  lines.push(
    `INSERT INTO categories (slug, name, bn, image, sort) VALUES (${q(c.slug)}, ${q(c.name)}, ${q(c.bn)}, ${q(c.image)}, ${i});`,
  );
});

products.forEach((p, i) => {
  lines.push(
    `INSERT INTO products (id, slug, name, bn, category, image, price, old_price, rating, reviews, badge, tag, description, sizes, out_of_stock, sort) VALUES (${q(p.id)}, ${q(p.slug)}, ${q(p.name)}, ${q(p.bn)}, ${q(p.category)}, ${q(p.image)}, ${q(p.price)}, ${q(p.oldPrice)}, ${q(p.rating ?? 4.8)}, ${q(p.reviews ?? 0)}, ${q(p.badge)}, ${q(p.tag)}, ${q(p.desc)}, ${q(p.sizes !== false)}, ${q(Boolean(p.outOfStock))}, ${i});`,
  );
});

DEFAULT_BANNERS.forEach((b, i) => {
  lines.push(
    `INSERT INTO banners (id, eyebrow, title, highlight, description, image, primary_label, primary_to, secondary_label, secondary_to, show_stats, active, sort) VALUES (${q(b.id)}, ${q(b.eyebrow)}, ${q(b.title)}, ${q(b.highlight)}, ${q(b.desc)}, ${q(b.image)}, ${q(b.primaryLabel)}, ${q(b.primaryTo)}, ${q(b.secondaryLabel)}, ${q(b.secondaryTo)}, ${q(b.showStats)}, ${q(b.active !== false)}, ${i});`,
  );
});

const social = Object.fromEntries(
  SOCIAL_CHANNELS.map((c) => [c.key, { value: c.defaultValue, enabled: c.defaultOn }]),
);

lines.push(
  `INSERT OR REPLACE INTO settings (key, value) VALUES ('store', ${q(JSON.stringify(DEFAULT_SETTINGS))});`,
  `INSERT OR REPLACE INTO settings (key, value) VALUES ('social', ${q(JSON.stringify(social))});`,
);

const out = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..', 'db', 'seed.sql');
writeFileSync(out, `${lines.join('\n')}\n`, 'utf8');
console.log(`wrote ${out}: ${categories.length} categories, ${products.length} products, ${DEFAULT_BANNERS.length} banners`);
